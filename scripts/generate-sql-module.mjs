/**
 * Generates `src/sql.generated.ts` from `sql/entity_id_generate.sql`.
 *
 * The SQL is embedded as a string constant so that `entity-id/sql` works
 * identically in every runtime — Node, Bun, Deno, a worker or a browser
 * bundle — without a filesystem read. `sql/entity_id_generate.sql` stays the
 * single source of truth and is also shipped as a raw file for `psql -f`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sqlPath = join(root, 'sql', 'entity_id_generate.sql');
const outPath = join(root, 'src', 'sql.generated.ts');

const sql = readFileSync(sqlPath, 'utf8');

const literal = JSON.stringify(sql);

const contents = `// AUTO-GENERATED by scripts/generate-sql-module.mjs — do not edit by hand.
// Source: sql/entity_id_generate.sql

/**
 * The canonical Postgres migration text, embedded verbatim so it is available
 * in every runtime without a filesystem read.
 *
 * @public
 */
export const ENTITY_ID_SQL: string = ${literal};
`;

writeFileSync(outPath, contents, 'utf8');
process.stdout.write(`generated ${outPath} (${sql.length} chars)\n`);
